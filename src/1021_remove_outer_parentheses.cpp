// ============================================================================
// 1021. 删除最外层的括号 (Remove Outermost Parentheses)
// 来源：https://leetcode.cn/problems/remove-outermost-parentheses/
// 难度：简单
//
// 题目：有效括号字符串 s 可唯一分解为若干「原语」之和 s = P1 + P2 + ... + Pk，
//       每个 Pi 是非空有效括号串且自身不可再拆分。
//       删除每个原语的最外层括号，返回处理后的字符串。
//
// 示例：s = "(()())(())"  ->  "()()()"
// ============================================================================
//
// 【思路】
//
// 关键观察：一个原语的最外层括号，恰好是「从深度 0 进到深度 1」的那个 '('，
// 以及「从深度 1 回到深度 0」的那个 ')'。所以只要跟踪当前嵌套深度：
//
//   - 遇到 '('：若此刻 depth > 0，说明它不在最外层，保留；然后 ++depth
//   - 遇到 ')'：先 --depth；若减完后 depth > 0，说明它不在最外层，保留
//
// 两处判断的时机故意不一样，这是本题唯一需要想清楚的地方：
// '(' 是「进入」括号，判断的是进入**之前**的深度；
// ')' 是「离开」括号，判断的是离开**之后**的深度。
//
// 为什么不用栈？用栈也能做，但栈里存的是字符，而这里真正需要的状态只有一个
// 整数深度。状态压缩掉之后空间从 O(n) 降到 O(1)。
//
// 等价视角：先按原语切分字符串，再对每段掐头去尾，结果完全一样。
// 计数深度只是同一件事的一遍扫描版本。
//
// 【复杂度】
//   时间：O(n)，每个字符访问一次。
//   空间：O(1) 额外空间（不计返回值本身占用的 O(n)）。
//
// 【易错点】
//   1. 两处判断的先后顺序不同，见上面的分析。写反了要么把最外层留下来，
//      要么把内层的丢掉。
//   2. 结果可能为空串，例如 s = "()()"，要保证这种情况正常返回空串。
//   3. 题目保证输入合法。如果自己封装成通用工具函数，应该加一层 balance 校验。
//
// 【面试追问】
//   1. 如果不保证输入是合法括号串？-> 额外维护 balance，任何时刻为负或扫完不为 0
//      就返回错误。
//   2. 如果要求只删除最内层括号？-> 需要先算出每个位置的最大深度，再据此判断。
//   3. 如果输入是长度 1e7 的串？-> 结果串记得 reserve，否则多次扩容会拖慢。
//
// ============================================================================

#include <cassert>
#include <cstddef>
#include <iostream>
#include <string>

namespace {

std::string remove_outer_parentheses(const std::string& s) {
    std::string result;
    result.reserve(s.size());

    int depth = 0;  // 当前所处的嵌套深度
    for (const char c : s) {
        if (c == '(') {
            // 进入括号：判断的是进入之前的深度
            if (depth > 0) {
                result.push_back(c);
            }
            ++depth;
        } else {
            // 离开括号：先减，再判断离开之后的深度
            --depth;
            if (depth > 0) {
                result.push_back(c);
            }
        }
    }
    return result;
}

}  // namespace

int main() {
    assert(remove_outer_parentheses("(()())(())") == "()()()");
    assert(remove_outer_parentheses("(()())(())(()(()))") == "()()()()(())");
    // 每个原语都只有一层，全部被剥掉，结果是空串
    assert(remove_outer_parentheses("()()").empty());
    // 单层原语
    assert(remove_outer_parentheses("(())") == "()");
    // 只有一个原语，剥掉一层后剩下里面那层
    assert(remove_outer_parentheses("((()))") == "(())");

    std::cout << "1021 remove_outer_parentheses: 全部用例通过\n";
    return 0;
}
